"""
Clause lists — valid clause identifiers per framework, from official sources.

``saaf/knowledge/clause_data/<KEY>.json`` holds, for each covered framework,
the identifiers (articles, paragraphs, sections, controls ...) that actually
exist in the official text, plus the source, the version used and the date it
was retrieved. The files are generated by ``tools/clause_sources/*.py``; update
them through a pull request that cites the sources (issue #7).

A listed identifier only proves that the clause EXISTS. It says nothing about
whether the clause means what a model claims, so references stay "unverified"
(see ``saaf/core/reference_check.py``).

Granularity (decision on issue #7): each framework is validated at the most
specific level an auditor can test against without losing the purpose of the
legislation. The level is stated per framework in ``granularity`` and
``granularity_rationale`` in its data file and summarised in ``GRANULARITY``
below. References more specific than the listed level are accepted when their
parent identifier is listed.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, Mapping, Tuple

CLAUSE_DATA_DIR = Path(__file__).parent / "clause_data"


@dataclass(frozen=True)
class Instrument:
    """One legal instrument / standard inside a framework entry."""

    code: str
    title: str
    version: str
    source: str
    retrieved_on: str
    identifiers: frozenset

    @property
    def kinds(self) -> frozenset:
        """Identifier prefixes present, e.g. {"art", "recital"}."""
        return frozenset(i.split(":", 1)[0] for i in self.identifiers)


@dataclass(frozen=True)
class ClauseList:
    framework_key: str
    granularity: str
    granularity_rationale: str
    instruments: Tuple[Instrument, ...]


def load_clause_lists(directory: Path = CLAUSE_DATA_DIR) -> Dict[str, ClauseList]:
    """Load every ``<KEY>.json`` file in ``directory`` (empty dict if absent)."""
    lists: Dict[str, ClauseList] = {}
    if not directory.is_dir():
        return lists
    for path in sorted(directory.glob("*.json")):
        raw = json.loads(path.read_text(encoding="utf-8"))
        lists[raw["framework_key"]] = ClauseList(
            framework_key=raw["framework_key"],
            granularity=raw["granularity"],
            granularity_rationale=raw["granularity_rationale"],
            instruments=tuple(
                Instrument(
                    code=i["code"],
                    title=i["title"],
                    version=i["version"],
                    source=i["source"],
                    retrieved_on=i["retrieved_on"],
                    identifiers=frozenset(i["identifiers"]),
                )
                for i in raw["instruments"]
            ),
        )
    return lists


CLAUSE_LISTS: Dict[str, ClauseList] = load_clause_lists()

