# Instrument qualifiers: restrict a locator to one instrument of a framework
# when the text names it (MiFID II Directive vs MiFIR; UK GDPR vs DPA 2018 ...).
INSTRUMENT_ALIASES: Mapping[str, Mapping[str, Tuple[str, ...]]] = {
    "MiFID_II": {
        "MiFIR": ("mifir", "regulation eu no 600 2014", "regulation eu 600 2014", "600 2014"),
        "MiFID_II": ("mifid ii", "mifid 2", "mifid", "directive 2014 65 eu",
                     "directive 2014 65", "2014 65"),
    },
    "UK_GDPR": {
        "DPA_2018": ("data protection act 2018", "data protection act", "dpa 2018"),
        "UK_GDPR": ("uk gdpr", "uk general data protection regulation"),
    },
}


def normalise_text(text: str) -> str:
    """Lower-case and collapse every run of non-alphanumerics to one space."""
    return re.sub(r"[^a-z0-9]+", " ", text.lower()).strip()


def _phrase_spans(norm: str, phrase: str) -> Iterable[Tuple[int, int]]:
    pattern = r"(?<![a-z0-9])" + re.escape(phrase) + r"(?![a-z0-9])"
    for m in re.finditer(pattern, norm):
        yield m.span()


def frameworks_named(text: str) -> Tuple[str, ...]:
    """Covered framework keys named in ``text`` (longest-match wins).

    A match wholly inside a longer match for another framework is dropped, so
    "UK GDPR Art. 5" names UK_GDPR only. Keys are returned in order of first
    appearance.
    """
    norm = normalise_text(text)
    hits = []  # (start, end, key)
    for key, aliases in FRAMEWORK_ALIASES.items():
        for alias in aliases:
            for start, end in _phrase_spans(norm, alias):
                hits.append((start, end, key))
    keep = []
    for start, end, key in hits:
        shadowed = any(
            k2 != key and s2 <= start and end <= e2 and (e2 - s2) > (end - start)
            for s2, e2, k2 in hits
        )
        if not shadowed:
            keep.append((start, key))
    keep.sort()
    seen = []
    for _, key in keep:
        if key not in seen:
            seen.append(key)
    return tuple(seen)


def instruments_named(framework_key: str, text: str) -> Tuple[str, ...]:
    """Instrument codes of ``framework_key`` explicitly named in ``text``."""
    table = INSTRUMENT_ALIASES.get(framework_key)
    if not table:
        return ()
    norm = normalise_text(text)
    hits = []
    for code, aliases in table.items():
        for alias in aliases:
            for start, end in _phrase_spans(norm, alias):
                hits.append((start, end, code))
    keep = {
        code
        for start, end, code in hits
        if not any(
            c2 != code and s2 <= start and end <= e2 and (e2 - s2) > (end - start)
            for s2, e2, c2 in hits
        )
    }
    return tuple(sorted(keep))
